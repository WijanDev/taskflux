export type SeedNameLocale = 'es' | 'en'

const SPANISH_LOCALE_WEIGHT = 0.8

export function pickSeedNameLocale(): SeedNameLocale {
  return Math.random() < SPANISH_LOCALE_WEIGHT ? 'es' : 'en'
}

function pickRandom<T>(items: readonly T[]): T {
  const index = Math.floor(Math.random() * items.length)
  return items[index]!
}

export function slugForSeedEmail(part: string): string {
  return part
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
}

export function buildSeedUserIdentity(
  usedEmails: Set<string>,
  emailDomain: string,
): { name: string; email: string } {
  const locale = pickSeedNameLocale()
  const givenNames =
    locale === 'es' ? SPANISH_GIVEN_NAMES : ENGLISH_GIVEN_NAMES
  const surnames = locale === 'es' ? SPANISH_SURNAMES : ENGLISH_SURNAMES

  for (let attempt = 0; attempt < 64; attempt += 1) {
    const givenName = pickRandom(givenNames)
    const surname = pickRandom(surnames)
    const name = `${givenName} ${surname}`
    const baseLocal = `${slugForSeedEmail(givenName)}_${slugForSeedEmail(surname)}`
    const local =
      attempt === 0 ? baseLocal : `${baseLocal}_${attempt + 1}`
    const email = `${local}@${emailDomain}`

    if (!usedEmails.has(email)) {
      usedEmails.add(email)
      return { name, email }
    }
  }

  const fallbackId = usedEmails.size + 1
  const email = `seed_user_${fallbackId}@${emailDomain}`
  usedEmails.add(email)
  return { name: `Seed User ${fallbackId}`, email }
}
